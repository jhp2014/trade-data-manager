// 순위 단면 번들 — GET /rank-sections 의 계약.
//
// ## 서버는 서수 원료만 굽는다 — N/M·테마·임계값은 전부 클라 읽기 시점 파생
// 단면 = **좌표 라벨(`group_members_point`)이 존재하는 (날짜, 분)** 마다 그날 유니버스 위에서 계산한
// 등락률·거래대금 서수(UN 기준 · 내림차순 · 경쟁 순위(동점 1,1,3) · carry-forward 참가/결손 제외 —
// core `rankSectionOf` 가 유일한 계산 주체고 클라 `/day-replay` 즉석 계산도 같은 함수).
//
// 모수가 격자 후보가 아니라 **라벨**인 이유(2026-09-18 A2, decisions.md 「구조 개편」): 종단 모수가
// 그룹 배정된 좌표로 좁아졌다 — 시트 행도 깔때기 술어도 타점 정보도 전부 라벨 좌표에서만 이 번들을
// 읽는다. 옛 모수(사건 봉 전부)는 34,202단면 · 98만 행이었고 그중 조회되는 건 라벨 분뿐이었다.
// 라벨 아닌 분은 **결손**이고 그게 맞다 — 탐색용 순위는 클라가 `/day-replay` 로 즉석 계산한다.
//
// ## 행은 **접혀서** 온다 — 그 분의 라벨 종목 ∪ 그 동료(테마 멤버 ∩ 그날 유니버스)
// 유니버스 전 종목을 그대로 실으면 단면당 268행이라 쓸데없이 무겁다. 술어가 실제로 읽는 건 **자기 서수
// + 소속 테마 동료의 서수**뿐이라(themeStrength.evalThemeStrength) 나머지는 아무도 안 읽는다 — 하루를
// 자세히 보는 화면(테마 순위 산점도·정규화 재적)은 `/day-replay` 로 그 하루만 즉석 계산하므로 이 번들과
// 무관하다. 닫힘 보장: 술어가 평가하는 (종목,분)은 정의상 그 분의 라벨 좌표다.
//
// ⚠ **접기는 서빙 시점에만** 한다 — 서버 파일 캐시는 유니버스 전 종목 서수 그대로다(저장물은 테마를
//   모른다). 그래서 시트에서 테마를 고쳐도 재굽기가 아니라 **다시 접기**로 끝난다.
// ⚠ 분모 `n` 은 접어도 **유니버스 전체 참가 수**다 — 접힌 행 수로 바꾸면 "몇 종목 중 몇 위"가 조용히 틀어진다.
// ⚠ 자기 서수는 테마가 없어도 항상 실린다 — 테마 무관 순위 조건이 나중에 생겨도 재설계가 없게.
//
// ## 크기 절약: 날짜당 코드 테이블 1벌 + **평탄 숫자 배열**
// `codes` = 그 **날짜의 접힌 종목 합집합**(유니버스 부분집합). 단면의 `rows` 는
// `[codeIdx, rate, amount, amount60]` 를 **이어 붙인 평탄 배열**(길이가 4의 배수 — **stride 4 가 계약**,
// codeIdx 오름차순)이고 **−1 = 결손**(그 분에 미개장·데이터 없음)이다. amount60 = 60분 창 누적 대금
// 서수(core BAKED_AMOUNT_WINDOW_MIN — 검색이 아는 유일한 T-창, 표시의 임의 T 는 클라 즉석 계산).
// 행이 아예 없으면 그 종목은 그 분의 관심 대상이 아니다(라벨도 동료도 아님).
//
// 왜 튜플 배열이 아니라 평탄인가(A2 **이전** 모수의 실측 34,202단면·988,390행 — 라벨 모수는 수백
// 단면이라 지금은 여유롭지만, 라벨이 수만이 되면 같은 자리로 돌아온다): 튜플이면 JSON 13.6MB 이고 파싱 뒤 힙에
// **작은 배열 100만 개**가 남는다. 평탄이면 회선이 줄고, 클라가 그대로 `Int32Array` 로 옮겨 담아
// 객체 수를 0 으로 만든다(격자 튜플 인코딩과 같은 이유 — 위치가 계약, 낟알은 숫자).
//
// ## sealed / pending — 분모(M)가 틀린 값을 조용히 주지 않는다
// sealed=false: 그 날짜 스냅샷이 아직 파일로 굳지 않아(수집 미완료) 서수가 부분 유니버스 위에서
// 계산됐을 수 있다 — 서버도 파일로 남기지 않고, 클라는 배지로 드러낼 수 있다.
// pending: 오늘(KST) 이후 날짜의 라벨 — 굽지도 서빙하지도 않는다(잠정 M 으로 필터를 판정하지 않는다).
//
// version 은 계산 규칙 버전(수동 무효화 손잡이) — 재료(분봉 원주가·기준가) 수리는 자동 감지되지 않으므로
// 이 값 상향(또는 캐시 삭제)이 처방이다(앵커 무관 계산 축과 같은 성질).

/** 단면 하나(그 분). `n` = 유니버스 전체 참가 수(접기와 무관한 분모). */
export interface WireRankSection {
    /** 단면 시각 "HH:MM". */
    time: string;
    /** 분모 — 그날 유니버스에서 등락률 서수가 선 종목 수(접힌 행 수가 아니다).
     *  ⚠ 지금 이 값을 읽는 소비자는 없다(화면의 N/M 은 클라 파생) — 접기 규칙의 일부라 계약에 남긴다. */
    n: number;
    /** 평탄 행 — `[codeIdx, rate, amount, amount60]` × 행 수(길이 **4의 배수**, codeIdx 오름차순). −1 = 결손. */
    rows: number[];
}

/** 날짜 하나의 단면 묶음. codes = 그날 **접힌** 종목 합집합(유니버스 부분집합). */
export interface RankSectionDate {
    date: string;
    /** 스냅샷이 굳은(수집 완료) 날짜인가 — false 면 서수가 부분 유니버스 위일 수 있다. */
    sealed: boolean;
    codes: string[];
    sections: WireRankSection[];
}

/** 전체 번들 — 클라가 통째 로드(수 MB raw, 회선은 gzip). */
export interface RankSectionBundle {
    /** 계산 규칙 버전 — 서버 캐시와 동기(클라는 표시만). */
    version: number;
    dates: RankSectionDate[];
    /** 굽지 않은 날짜(오늘 이후의 라벨) — "결손은 결손"으로 드러낸다.
     *  A2(2026-09-18) 로 **실제로 찬다**: 기대집합이 라벨 직결이라 오늘 붙인 라벨의 날짜가 여기 선다
     *  (옛 모수인 격자는 `date < 오늘` 만 구워 이 배열이 구조적으로 늘 비어 있었다).
     *  ⚠ 아직 **읽는 화면이 없다** — 오늘 붙인 라벨의 테마 술어·테마 줄은 말없이 결손으로 선다.
     *  배지를 붙이려면 `useRankSections().pending` 이 그 재료다(존재 지도·sealed 배지와 같은 결). */
    pending: string[];
}
