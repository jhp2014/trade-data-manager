// 순위 단면 번들 — GET /rank-sections 의 계약.
//
// ## 서버는 서수 원료만 굽는다 — N/M·테마·임계값은 전부 클라 읽기 시점 파생
// 단면 = **격자의 신고가 캔들이 존재하는 (날짜, 분)** 마다 그날 유니버스 위에서 계산한 등락률·거래대금
// 서수(UN 기준 · 내림차순 · 경쟁 순위(동점 1,1,3) · carry-forward 참가/결손 제외 — core `rankSectionOf`
// 가 유일한 계산 주체고 클라가 `/day-replay` 로 즉석 계산할 때도 같은 함수를 쓴다).
//
// 모수가 타점이 아니라 **후보 캔들**인 이유(2026-09-01): 타점이 읽기 층 파생물이 되면서 서버가 "어느
// 분을 구울지"를 알 수 없게 됐는데, `Point ⊆ 신고가 캔들`이라 후보 전체를 구우면 **정의(게이트·병합·
// 양봉)를 굴려도 서버 왕복이 0**이다. 서버는 격자를 이미 갖고 있으므로 기대집합을 스스로 뽑는다.
//
// ## 행은 **접혀서** 온다 — 그 분의 후보 종목 ∪ 그 동료(테마 멤버 ∩ 그날 유니버스)
// 유니버스 전 종목을 그대로 실으면 34,202단면 × 268종목 ≈ 9.2M행이라 클라가 못 든다. 술어가 실제로
// 읽는 건 **자기 서수 + 소속 테마 동료의 서수**뿐이라(themeStrength.evalThemeStrength) 나머지는 아무도
// 안 읽는다 — 하루를 자세히 보는 화면(테마 순위 산점도·정규화 재적)은 `/day-replay` 로 그 하루만 즉석
// 계산하므로 이 번들과 무관하다. 닫힘 보장: 술어가 평가하는 (종목,분)은 정의상 그 분의 후보다.
//
// ⚠ **접기는 서빙 시점에만** 한다 — 서버 파일 캐시는 유니버스 전 종목 서수 그대로다(저장물은 테마를
//   모른다). 그래서 시트에서 테마를 고쳐도 재굽기가 아니라 **다시 접기**로 끝난다.
// ⚠ 분모 `n` 은 접어도 **유니버스 전체 참가 수**다 — 접힌 행 수로 바꾸면 "몇 종목 중 몇 위"가 조용히 틀어진다.
// ⚠ 자기 서수는 테마가 없어도 항상 실린다 — 테마 무관 순위 조건이 나중에 생겨도 재설계가 없게.
//
// ## 크기 절약: 날짜당 코드 테이블 1벌 + **평탄 숫자 배열**
// `codes` = 그 **날짜의 접힌 종목 합집합**(유니버스 부분집합). 단면의 `rows` 는 `[codeIdx, rate, amount]`
// 를 **이어 붙인 평탄 배열**(길이가 3의 배수, codeIdx 오름차순)이고 **−1 = 결손**(그 분에 미개장·데이터
// 없음)이다. 행이 아예 없으면 그 종목은 그 분의 관심 대상이 아니다(후보도 동료도 아님).
//
// 왜 튜플 배열이 아니라 평탄인가(실측 34,202단면·988,390행): 튜플이면 JSON 13.6MB 이고 파싱 뒤 힙에
// **작은 배열 100만 개**가 남는다. 평탄이면 회선이 줄고, 클라가 그대로 `Int32Array` 로 옮겨 담아
// 객체 수를 0 으로 만든다(격자 튜플 인코딩과 같은 이유 — 위치가 계약, 낟알은 숫자).
//
// ## sealed / pending — 분모(M)가 틀린 값을 조용히 주지 않는다
// sealed=false: 그 날짜 스냅샷이 아직 파일로 굳지 않아(수집 미완료) 서수가 부분 유니버스 위에서
// 계산됐을 수 있다 — 서버도 파일로 남기지 않고, 클라는 배지로 드러낼 수 있다.
// pending: 오늘(KST) 이후 날짜의 후보 — 굽지도 서빙하지도 않는다(잠정 M 으로 필터를 판정하지 않는다).
//
// version 은 계산 규칙 버전(수동 무효화 손잡이) — 재료(분봉 원주가·기준가) 수리는 자동 감지되지 않으므로
// 이 값 상향(또는 캐시 삭제)이 처방이다(앵커 무관 계산 축과 같은 성질).

/** 단면 하나(그 분). `n` = 유니버스 전체 참가 수(접기와 무관한 분모). */
export interface WireRankSection {
    /** 단면 시각 "HH:MM". */
    time: string;
    /** 분모 — 그날 유니버스에서 등락률 서수가 선 종목 수(접힌 행 수가 아니다).
     *  ⚠ 지금 이 값을 읽는 소비자는 없다(화면의 N/M 은 클라 파생) — 접기 규칙의 일부라 계약에 남긴다. */
    n: number;
    /** 평탄 행 — `[codeIdx, rate, amount]` × 행 수(길이 3의 배수, codeIdx 오름차순). −1 = 결손. */
    rows: number[];
}

/** 날짜 하나의 단면 묶음. codes = 그날 **접힌** 종목 합집합(유니버스 부분집합). */
export interface RankSectionDate {
    date: string;
    /** 스냅샷이 굳은(수집 완료) 날짜인가 — false 면 서수가 부분 유니버스 위일 수 있다. */
    sealed: boolean;
    codes: string[];
    sections: WireRankSection[];
}

/** 전체 번들 — 클라가 통째 로드(수 MB raw, 회선은 gzip). */
export interface RankSectionBundle {
    /** 계산 규칙 버전 — 서버 캐시와 동기(클라는 표시만). */
    version: number;
    dates: RankSectionDate[];
    /** 굽지 않은 날짜(오늘 이후의 후보) — "결손은 결손"으로 드러낸다.
     *  ⚠ 지금은 **구조적으로 항상 빈다**: 격자가 `date < 오늘` 만 굽기 때문에 기대집합에 오늘·미래가
     *  아예 안 온다. 격자가 당일을 굽게 되면 그때 살아나는 자리라 계약·분기를 남겨 둔다. */
    pending: string[];
}
