// core/market/domain/map — 유사도 맵. 축이 없는 2차원 평면.
//
// **점은 항목이 아니라 그룹이다.** 처음엔 종목·날짜를 낱개로 흩뿌리려 했는데, 그러면 모든 쌍 사이에
// 거리가 생긴다 — 실제로 주장하려던 건 일부 이웃 관계뿐이고 나머지는 배치하다 생긴 부산물인데,
// 나중에 그게 의미로 읽힌다. 수천 개를 손으로 놓는 노동도 거기서 나왔다.
//
// 그래서 평면은 **그룹 사이의 구조를 보는 곳**이 됐다: 그룹 안 그룹(중첩) · 멤버 겹침으로 드러나는
// 징검다리 · 손으로 잡아 둔 대략의 자리. 묶고 쪼개는 판단은 골격 패널에서 형태를 보며 하고
// (거기선 닮은 골격이 한눈에 보인다), 여기서는 그 결과의 관계만 본다.
//
// **가까움은 주장이고, 멂은 무주장이다** — 붙여 놓은 둘은 닮았다는 말이지만 멀리 있는 둘은
// "안 닮았다"가 아니라 아직 아무 말도 안 한 것이다. 좌표·부모는 그룹이 든다(domain/review/group.ts).

/**
 * 이 평면에 올릴 수 있는 그룹의 층위. 그룹도 같은 값을 들고, 올릴 때 일치하는지 저장 경로가 본다.
 * 하루 그룹의 멤버는 (종목·날짜)고 타점 그룹의 멤버는 (종목·날짜·시각)이라, 섞으면 한 평면에서
 * 두 층위의 겹침을 같은 선으로 그리게 된다.
 */
export type MapScope = "day" | "point";

/**
 * 한 장의 평면. **이름이 곧 정체성**이다 — 전역 유일이고(같은 이름 둘은 사고다), 계약은 이걸로만 지목한다.
 * DB 의 surrogate id 는 저장소 안에 남지만 밖으로 나오지 않는다: 읽기는 로컬 미러 · 쓰기는 Supabase 라
 * 두 DB 가 각자 id 를 발급하고, 미러 전체교체 때 로컬 id 는 통째로 갈린다. id 가 계약에 있으면
 * 동기화를 건넌 순간 다른 행을 가리킨다 — 자연키는 그 문제가 원리적으로 없다.
 */
export interface SimilarityMap {
    name: string;
    scope: MapScope;
}
