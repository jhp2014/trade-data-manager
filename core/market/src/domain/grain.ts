// 알갱이(grain) — "이 판단·값·조건이 하루 단위인가 타점 단위인가"의 **한 어휘**.
//
// 같은 "day" | "point" 가 네 곳(그룹 scope · 판단 축 scope · 계산 축 grain · 깔때기 Grain)에서 따로
// 정의돼 있었다. 구조적 타이핑이라 동작은 같았지만, 어휘가 흩어지면 "이게 다 같은 개념인가?"를 코드가
// 답하지 못한다 — 층위 규칙(하루 단계가 타점보다 앞, 칸이 곧 선언)은 이 값들이 **같은 어휘라는 사실**
// 위에 서 있으므로, 정의를 한 곳에 두고 나머지는 별칭으로 입는다.
export type Grain = "day" | "point";
